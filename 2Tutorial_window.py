# Tutorial, how to make window with Tkinter
# First, we need to import Tkinter library
import tkinter as tk

# Create window
window = tk.Tk()

# Set the window title name
window.title("The Title")

# Size of window
window.geometry("600x400")

# Start the main loop so the window stays open forever
window.mainloop()

# Congratulations! You've just made your own window :D